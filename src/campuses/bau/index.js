// Baekseok Arts University Seoul: 14 destructible units (13 buildings + one bridge), no protected buildings (user 2026-10-26).
import { WORLD_UNITS_PER_METER, GEO_ORIGIN, BAU_PLACEMENTS, BAU_BUILDING_BASE, BAU_HEIGHT_GRIDS, BAU_HEIGHT_RANGE_M, BAU_ENV_IDS, BAU_ENV_MANIFEST_IDS, BAU_LOOK, BAU_ZONES, BAU_DISPLAY, BAU_PROVENANCE } from './data.js';
import { BAU_FOOTPRINTS } from './footprints.js';
import { BAU_PROTECTED } from './protected.js';
import { createBauGroundLook } from './ground-look.js';

const MODEL_IDS = Object.freeze(BAU_PLACEMENTS.map(p => p.id));
const asset = file => new URL(`../../../assets/campuses/bau/${file}`, import.meta.url).href;
const HAZE = BAU_DISPLAY.haze, FADE = BAU_DISPLAY.fade;

export const BAU = Object.freeze({
  id: 'bau',
  meta: Object.freeze({ school: '백석예술대학교', campus: '서울', short: '백석예대', modelNoun: '백석예대' }),
  geo: Object.freeze({ origin: GEO_ORIGIN, worldUnitsPerMeter: WORLD_UNITS_PER_METER }),
  placements: BAU_PLACEMENTS,
  approvedCount: BAU_PLACEMENTS.length,
  additionalCount: 0,
  coreIds: Object.freeze(['arts', 'education', 'vision', 'freedom', 'truth'].filter(id => MODEL_IDS.includes(id))),
  // 중앙 진입축의 교육동·비전센터·연결교를 안내문 위로 배치. 앞쪽 자유동 가림을 줄이는 학교별 각도.
  startBuildingId: 'education',
  camera: Object.freeze({ playElevation: 35, tiltNear: 22 }),
  view: Object.freeze({ get startFrame() { return (globalThis.innerWidth || 1280) < 600
    ? { min: [-12, -21, -27], max: [14, 3, -2], azimuth: 0.75 }
    : { min: [-17, -14, -28], max: [18, 11, -2], azimuth: 0.75 }; } }),
  models: Object.freeze({
    manifests: Object.freeze([
      Object.freeze({ url: asset('manifest.json'), expectedIds: MODEL_IDS }),
      Object.freeze({ url: asset('environment.json'), expectedIds: BAU_ENV_MANIFEST_IDS }),
    ]),
    proceduralIds: Object.freeze([]),
    createProceduralSource: () => { throw new Error('No procedural buildings in this campus'); },
    enhanceFacade: () => ({ stats: {}, dispose() {} }),
  }),
  terrain: Object.freeze({ heightGrids: BAU_HEIGHT_GRIDS, buildingBase: BAU_BUILDING_BASE,
    source: 'Relative terrain estimate (Copernicus GLO-30, building-filled, forest lowered + place / photo level evidence, pilot/bau-seoul); not a survey' }),
  environment: Object.freeze({ provenance: BAU_PROVENANCE, sourceNote: 'OSM ground surfaces and surroundings (© OpenStreetMap contributors, ODbL); heights, planting and the place models estimated' }),
  ground: Object.freeze({
    baked: Object.freeze({ envIds: BAU_ENV_IDS, castShadow: Object.freeze([]), materialHook: createBauGroundLook(BAU_LOOK, BAU_ZONES, BAU_DISPLAY.backdropFade),
      // context.json display fade (preview.js FADE): campus clear to r0, the backdrop melts into the haze by r1
      fade: Object.freeze({ centre_m: Object.freeze([...FADE.centreEN]), near_m: FADE.r0_m, far_m: FADE.r1_m, ...(FADE.linearShare ? { linear: FADE.linearShare } : {}), colour: HAZE }), playMargin_m: 30,
      source: 'pilot/bau-seoul preview ground + planting + landscape + context, baked' }),
  }),
  // All 14 model units break; the empty protected list is generated by the package builder.
  protected: Object.freeze({
    ...(BAU_PROTECTED.length ? { manifestURL: asset('protected/manifest.json') } : {}),
    models: BAU_PROTECTED,
  }),
  // Hazard tape around every destructible building only (src/engine/hazard-tape.js): none on the protected models or the context.
  hazardTape: Object.freeze({ footprints: BAU_FOOTPRINTS }),
  scene: Object.freeze({
    // Same light as the Bau preview: sun (-190, 360, -40), target origin, coordinates halved.
    background: HAZE, fog: Object.freeze({ color: HAZE, near: 650, far: 2200 }),
    hemisphere: Object.freeze({ sky: '#ffffff', ground: '#7d8a78', intensity: 1.35 }),
    sun: Object.freeze({ color: '#fff4e2', intensity: 3.1, position: Object.freeze([-95, 180, -20]), shadowSpan: 280 }),
    floor: Object.freeze({ color: '#c9cbc8', hidden: true, y: BAU_HEIGHT_RANGE_M[0] * WORLD_UNITS_PER_METER - .3 }),
  }),
});
export default BAU;
