// 경기대학교 수원캠퍼스 (local only, public:false): 44 destructible buildings, no protected buildings (광교 씨름전용체육관 breaks: user 2026-10-28).
// Package: scripts/campuses/kyonggi/build-package.mjs from pilot/kyonggi-suwon (copy of the ajou runtime package; the pilot is an ajou-suwon preview copy).
import { WORLD_UNITS_PER_METER, GEO_ORIGIN, KG_PLACEMENTS, KG_BUILDING_BASE, KG_HEIGHT_GRIDS, KG_HEIGHT_RANGE_M, KG_ENV_IDS, KG_ENV_MANIFEST_IDS, KG_LOOK, KG_ZONES, KG_DISPLAY, KG_PROVENANCE } from './data.js';
import { KG_FOOTPRINTS } from './footprints.js';
import { KG_PROTECTED } from './protected.js';
import { createKyonggiGroundLook } from './ground-look.js';

const MODEL_IDS = Object.freeze(KG_PLACEMENTS.map(p => p.id));
const asset = file => new URL(`../../../assets/campuses/kyonggi/${file}`, import.meta.url).href;
const HAZE = KG_DISPLAY.haze, FADE = KG_DISPLAY.fade;

export const KYONGGI = Object.freeze({
  id: 'kyonggi',
  meta: Object.freeze({ school: '경기대학교', campus: '수원캠퍼스', short: '경기대 수원', modelNoun: '경기대' }),
  geo: Object.freeze({ origin: GEO_ORIGIN, worldUnitsPerMeter: WORLD_UNITS_PER_METER }),
  placements: KG_PLACEMENTS,
  approvedCount: KG_PLACEMENTS.length,
  additionalCount: 0,
  coreIds: Object.freeze(['tele', 'library', 'jinri', 'jiphyeon', 'hoyeon'].filter(id => MODEL_IDS.includes(id))),
  // 시작 화면 주인공 = 텔레컨벤션센터(앞으로 기운 유리탑·부채꼴 지붕). 상자는 월드 단위(m x 0.5, z = -N), azimuth = 대상 -> 카메라(camera.js).
  startBuildingId: 'tele',
  view: Object.freeze({ get startFrame() { return (globalThis.innerWidth || 1280) < 600
    ? { min: [-37.5, -1, -97.0], max: [-11.5, 10, -65.0], azimuth: 2.62, elevationDegrees: 20 }
    : { min: [-36.3, -1, -105.2], max: [3.7, 10, -61.2], azimuth: 2.62, elevationDegrees: 15 }; } }),   // 북북동(주차장 쪽)에서 기운 유리탑 옆모습; 상자를 카메라 쪽으로 당겨 텔레가 화면 가운데 안내문 위로 오게(후보 7개 시험, screens-b·c)
  models: Object.freeze({
    manifests: Object.freeze([
      Object.freeze({ url: asset('manifest.json'), expectedIds: MODEL_IDS }),
      Object.freeze({ url: asset('environment.json'), expectedIds: KG_ENV_MANIFEST_IDS }),
    ]),
    proceduralIds: Object.freeze([]),
    createProceduralSource: () => { throw new Error('No procedural buildings in this campus'); },
    enhanceFacade: () => ({ stats: {}, dispose() {} }),
  }),
  terrain: Object.freeze({ heightGrids: KG_HEIGHT_GRIDS, buildingBase: KG_BUILDING_BASE,
    source: 'Relative terrain estimate (Copernicus GLO-30, building-filled, forest lowered + place / photo level evidence, pilot/kyonggi-suwon); not a survey' }),
  environment: Object.freeze({ provenance: KG_PROVENANCE, sourceNote: 'OSM ground surfaces and surroundings (© OpenStreetMap contributors, ODbL); heights, planting and the place models estimated' }),
  ground: Object.freeze({
    baked: Object.freeze({ envIds: KG_ENV_IDS, castShadow: Object.freeze([]), materialHook: createKyonggiGroundLook(KG_LOOK, KG_ZONES, KG_DISPLAY.backdropFade),
      // context.json display fade (preview.js FADE): campus clear to r0, the backdrop melts into the haze by r1
      fade: Object.freeze({ centre_m: Object.freeze([...FADE.centreEN]), near_m: FADE.r0_m, far_m: FADE.r1_m, ...(FADE.linearShare ? { linear: FADE.linearShare } : {}), colour: HAZE }), playMargin_m: 30,
      source: 'pilot/kyonggi-suwon preview ground + planting + landscape + context, baked' }),
  }),
  // All 44 buildings break; the empty protected list is generated by the package builder.
  protected: Object.freeze({
    ...(KG_PROTECTED.length ? { manifestURL: asset('protected/manifest.json') } : {}),
    models: KG_PROTECTED,
  }),
  // Hazard tape around every destructible building only (src/engine/hazard-tape.js): none on the protected models or the context.
  hazardTape: Object.freeze({ footprints: KG_FOOTPRINTS }),
  scene: Object.freeze({
    // Same light as the Kyonggi preview (pilot/kyonggi-suwon/preview.js): sun (-190, 360, -40), target origin, coordinates halved.
    background: HAZE, fog: Object.freeze({ color: HAZE, near: 650, far: 2200 }),
    hemisphere: Object.freeze({ sky: '#ffffff', ground: '#7d8a78', intensity: 1.35 }),
    sun: Object.freeze({ color: '#fff4e2', intensity: 3.1, position: Object.freeze([-95, 180, -20]), shadowSpan: 280 }),
    floor: Object.freeze({ color: '#c9cbc8', hidden: true, y: KG_HEIGHT_RANGE_M[0] * WORLD_UNITS_PER_METER - .3 }),
  }),
});
export default KYONGGI;
