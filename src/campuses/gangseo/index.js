// Gangseo University Seoul: eight destructible buildings, no protected buildings (user 2026-10-24).
import { WORLD_UNITS_PER_METER, GEO_ORIGIN, GANGSEO_PLACEMENTS, GANGSEO_BUILDING_BASE, GANGSEO_HEIGHT_GRIDS, GANGSEO_HEIGHT_RANGE_M, GANGSEO_ENV_IDS, GANGSEO_ENV_MANIFEST_IDS, GANGSEO_LOOK, GANGSEO_ZONES, GANGSEO_DISPLAY, GANGSEO_PROVENANCE } from './data.js';
import { GANGSEO_FOOTPRINTS } from './footprints.js';
import { GANGSEO_PROTECTED } from './protected.js';
import { createSkkuGroundLook } from '../skku/ground-look.js';

const MODEL_IDS = Object.freeze(GANGSEO_PLACEMENTS.map(p => p.id));
const asset = file => new URL(`../../../assets/campuses/gangseo/${file}`, import.meta.url).href;
const HAZE = GANGSEO_DISPLAY.haze, FADE = GANGSEO_DISPLAY.fade;

export const GANGSEO = Object.freeze({
  id: 'gangseo',
  meta: Object.freeze({ school: '강서대학교', campus: '서울', short: '강서대', modelNoun: '강서대' }),
  geo: Object.freeze({ origin: GEO_ORIGIN, worldUnitsPerMeter: WORLD_UNITS_PER_METER }),
  placements: GANGSEO_PLACEMENTS,
  approvedCount: GANGSEO_PLACEMENTS.length,
  additionalCount: 0,
  coreIds: Object.freeze(['holton', 'harding', 'chesshir'].filter(id => MODEL_IDS.includes(id))),
  // 정문 오르막에서 홀튼관으로 향하는 시작 축. PC는 정문 진입축을 포함하고 390은 홀튼·앞 포장에 집중한다. 하향20°/줌14°는 공유 기본값.
  startBuildingId: 'holton',
  view: Object.freeze({ get startFrame() { return (globalThis.innerWidth || 1280) < 600
    ? { min: [-32, -1, -27], max: [-9, 13, -6], azimuth: 0.8 }
    : { min: [-40, -2, -28], max: [-4, 14, -1], azimuth: 0.6 }; } }),
  models: Object.freeze({
    manifests: Object.freeze([
      Object.freeze({ url: asset('manifest.json'), expectedIds: MODEL_IDS }),
      Object.freeze({ url: asset('environment.json'), expectedIds: GANGSEO_ENV_MANIFEST_IDS }),
    ]),
    proceduralIds: Object.freeze([]),
    createProceduralSource: () => { throw new Error('No procedural buildings in this campus'); },
    enhanceFacade: () => ({ stats: {}, dispose() {} }),
  }),
  terrain: Object.freeze({ heightGrids: GANGSEO_HEIGHT_GRIDS, buildingBase: GANGSEO_BUILDING_BASE,
    source: 'Relative terrain estimate (Copernicus GLO-30, building-filled, forest lowered + place / photo level evidence, pilot/gangseo-seoul); not a survey' }),
  environment: Object.freeze({ provenance: GANGSEO_PROVENANCE, sourceNote: 'OSM ground surfaces and surroundings (© OpenStreetMap contributors, ODbL); heights, planting and the place models estimated' }),
  ground: Object.freeze({
    baked: Object.freeze({ envIds: GANGSEO_ENV_IDS, castShadow: Object.freeze([]), materialHook: createSkkuGroundLook(GANGSEO_LOOK, GANGSEO_ZONES),
      // context.json display fade (preview.js FADE): campus clear to r0, the backdrop melts into the haze by r1
      fade: Object.freeze({ centre_m: Object.freeze([...FADE.centreEN]), near_m: FADE.r0_m, far_m: FADE.r1_m, ...(FADE.linearShare ? { linear: FADE.linearShare } : {}), colour: HAZE }), playMargin_m: 30,
      source: 'pilot/gangseo-seoul preview ground + planting + landscape + context, baked' }),
  }),
  // All eight buildings break; the empty protected list is generated by the package builder.
  protected: Object.freeze({
    ...(GANGSEO_PROTECTED.length ? { manifestURL: asset('protected/manifest.json') } : {}),
    models: GANGSEO_PROTECTED,
  }),
  // Hazard tape around every destructible building only (src/engine/hazard-tape.js): none on the protected models or the context.
  hazardTape: Object.freeze({ footprints: GANGSEO_FOOTPRINTS }),
  scene: Object.freeze({
    // Same light as the Gangseo preview: sun (-190, 360, -40), target origin, coordinates halved.
    background: HAZE, fog: Object.freeze({ color: HAZE, near: 650, far: 2200 }),
    hemisphere: Object.freeze({ sky: '#ffffff', ground: '#7d8a78', intensity: 1.35 }),
    sun: Object.freeze({ color: '#fff4e2', intensity: 3.1, position: Object.freeze([-95, 180, -20]), shadowSpan: 280 }),
    floor: Object.freeze({ color: '#c9cbc8', hidden: true, y: GANGSEO_HEIGHT_RANGE_M[0] * WORLD_UNITS_PER_METER - .3 }),
  }),
});
export default GANGSEO;
